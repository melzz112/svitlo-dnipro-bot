def main():
    fails = []

    def check(name, got, exp):
        if got != exp:
            fails.append(f"{name}: отримали {got}, чекали {exp}")

    for text, exp in WITH_GROUP:
        r = parse_user(text)
        check(text[:60], (r["event"], r["groups"]) if r else None, exp)
    for text, exp in NO_GROUP_REPORTS:
        r = parse_user(text)
        check(text[:60], r["event"] if r else None, exp)
    for text in NOT_REPORTS:
        r = parse_user(text)
        check(text[:60], (r["event"], r["groups"]) if r else None, None)
    for text, parent, exp in REPLIES:
        r = parse_user(text, parent)
        check(f"{text!r} у відповідь на {parent!r}", (r["event"], r["groups"]) if r else None, exp)
    for text, exp in DISTRICTS:
        check(f"район: {text}", find_district(text), exp)
    for text, exp in STREETS:
        check(f"вулиця: {text}", find_street(text), exp)

    total = len(WITH_GROUP) + len(NO_GROUP_REPORTS) + len(NOT_REPORTS) + len(REPLIES) + len(DISTRICTS) + len(STREETS)
    for f in fails:
        print("FAIL", f)
    print(f"{total - len(fails)}/{total} ok")
    sys.exit(1 if fails else 0)


if __name__ == "__main__":
    main()
